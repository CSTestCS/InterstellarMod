package com.cstestcs.interstellar.core.race;

import com.cstestcs.interstellar.core.image.SkinPainter;
import com.cstestcs.interstellar.core.model.JavaModelWriter;
import com.cstestcs.interstellar.core.model.ModelDef;
import com.cstestcs.interstellar.core.space.ForeignWorlds;
import java.util.EnumMap;
import java.util.Map;
import java.util.SplittableRandom;

import static com.cstestcs.interstellar.core.race.RaceDetails.Key.*;

/**
 * Generates one alien race (plus two subraces) per foreign world: details file, a Blockbench-format head model and
 * procedurally painted skins. Everything is written as ordinary race files, so players can edit or replace them.
 */
public final class AlienRaces {
    private AlienRaces() {}

    private static final String[] TAILS = { "none", "none", "lizard", "dragon", "demon", "fish", "cat", "monkey" };
    private static final Map<ForeignWorlds.Theme, String> FAVORITES = Map.ofEntries(
            Map.entry(ForeignWorlds.Theme.CRYSTAL, "minecraft:amethyst_shard"),
            Map.entry(ForeignWorlds.Theme.MAGMA, "minecraft:blaze_rod"),
            Map.entry(ForeignWorlds.Theme.VOID, "minecraft:ender_pearl"),
            Map.entry(ForeignWorlds.Theme.FUNGAL, "minecraft:glow_berries"),
            Map.entry(ForeignWorlds.Theme.FROZEN, "minecraft:blue_ice"),
            Map.entry(ForeignWorlds.Theme.TOXIC, "minecraft:slime_ball"),
            Map.entry(ForeignWorlds.Theme.DUNE, "minecraft:gold_ingot"),
            Map.entry(ForeignWorlds.Theme.REEF, "minecraft:prismarine_crystals"),
            Map.entry(ForeignWorlds.Theme.RUST, "minecraft:copper_ingot"),
            Map.entry(ForeignWorlds.Theme.ECHO, "minecraft:echo_shard"),
            Map.entry(ForeignWorlds.Theme.HONEY, "minecraft:honeycomb"),
            Map.entry(ForeignWorlds.Theme.BONE, "minecraft:bone_meal"));

    static void write(Map<String, byte[]> out) {
        for (ForeignWorlds.World w : ForeignWorlds.all()) writeWorld(out, w);
    }

    private static void writeWorld(Map<String, byte[]> out, ForeignWorlds.World w) {
        SplittableRandom r = new SplittableRandom(w.seed() ^ 0xA11E7L);
        String id = w.alienRaceId();
        String faction = id;
        int roll = r.nextInt(10);
        String disposition = roll < 6 ? "hostile" : roll < 9 ? "neutral" : "passive";

        Map<RaceDetails.Key, String> v = new EnumMap<>(RaceDetails.Key.class);
        v.put(RACE_NAME, w.alienName());
        v.put(GENDER, "null");
        v.put(TAIL_TYPE, TAILS[r.nextInt(TAILS.length)]);
        v.put(HOME_DIMENSION, w.dimensionId());
        v.put(MOB_CONSTRAINT, "interstellar:alien");
        v.put(POPULATION_PERCENT, "100");
        v.put(DEFAULT_DISPOSITION, disposition);
        v.put(FAVORITE_ITEM, FAVORITES.get(w.theme()));
        v.put(FAVORITE_ITEM_POTENCY, Integer.toString(5 + r.nextInt(21)));
        v.put(RACE_SIZE, String.format(java.util.Locale.ROOT, "%.2f", 0.8 + r.nextDouble() * 0.6));
        v.put(WEAPONS, "gun");
        v.put(REPLACE_BODY, "true");
        v.put(BODY_TYPE, "any");
        v.put(SLIM_ARMS, Boolean.toString(r.nextBoolean()));
        v.put(FACTION, faction);
        v.put(ENEMIES, "humans, villagers, illagers");
        v.put(HEALTH_MULTIPLIER, String.format(java.util.Locale.ROOT, "%.2f", 1.0 + r.nextDouble()));
        v.put(SPEED_MULTIPLIER, String.format(java.util.Locale.ROOT, "%.2f", 0.9 + r.nextDouble() * 0.4));
        v.put(DAMAGE_MULTIPLIER, "1.0");
        v.put(TRAITS, traitFor(w.theme()));
        v.put(NAMES, names(r, w.alienName()));
        v.put(PLAYER_SELECTABLE, "false");
        v.put(WEAPON_TIER, Integer.toString(1 + r.nextInt(3)));
        v.put(WEAPON_THEME, w.theme().weaponTheme);
        out.put(id + "_details.txt", DefaultRaces.text(RaceDetailsParser.write(
                "Alien race native to " + w.displayName() + " (" + w.dimensionId() + "), generated by Interstellar.", v)));

        SkinPainter.Palette palette = SkinPainter.randomPalette(w.seed());
        out.put(id + "_skin.png", SkinPainter.paintBiped(palette, w.seed()).toPng());
        out.put(id + "_skin_01.png", SkinPainter.paintBiped(palette, w.seed() + 1).toPng());
        out.put(id + "_headskin.png", SkinPainter.paintHeadTexture(palette, w.seed()).toPng());
        out.put(id + "_head.java", DefaultRaces.text(JavaModelWriter.write(id + "_head", head(r))));

        Map<RaceDetails.Key, String> elite = new EnumMap<>(RaceDetails.Key.class);
        elite.put(SUBRACE, id);
        elite.put(RACE_NAME, w.alienName() + " Elite");
        elite.put(POPULATION_PERCENT, "12");
        elite.put(DEFAULT_DISPOSITION, "hostile");
        elite.put(RACE_SIZE, "1.35");
        elite.put(HEALTH_MULTIPLIER, "2.5");
        elite.put(DAMAGE_MULTIPLIER, "1.5");
        elite.put(FAVORITE_ITEM_POTENCY, "2");
        elite.put(WEAPON_TIER, "4");
        out.put(id + "_elite_details.txt", DefaultRaces.text(RaceDetailsParser.write("Elite subrace of " + w.alienName() + ".", elite)));

        Map<RaceDetails.Key, String> scout = new EnumMap<>(RaceDetails.Key.class);
        scout.put(SUBRACE, id);
        scout.put(RACE_NAME, w.alienName() + " Scout");
        scout.put(GENDER, r.nextBoolean() ? "female" : "male");
        scout.put(POPULATION_PERCENT, "20");
        scout.put(RACE_SIZE, "0.8");
        scout.put(SPEED_MULTIPLIER, "1.35");
        scout.put(WEAPON_TIER, "1");
        out.put(id + "_scout_details.txt", DefaultRaces.text(RaceDetailsParser.write("Scout subrace of " + w.alienName() + ".", scout)));
    }

    private static String traitFor(ForeignWorlds.Theme t) {
        return switch (t) {
            case MAGMA, DUNE, BONE -> "fire_immune";
            case REEF -> "water_breathing";
            case VOID -> "slow_fall, no_fall_damage";
            case ECHO -> "night_vision";
            case CRYSTAL -> "night_vision";
            case TOXIC -> "regeneration";
            case FUNGAL, HONEY -> "regeneration";
            default -> "";
        };
    }

    private static String names(SplittableRandom r, String base) {
        StringBuilder sb = new StringBuilder();
        String[] syl = { "ka", "zu", "rik", "th", "ol", "ix", "va", "mo", "qe", "ssa", "dra", "un" };
        for (int i = 0; i < 6; i++) {
            if (i > 0) sb.append(", ");
            String n = syl[r.nextInt(syl.length)] + syl[r.nextInt(syl.length)] + (r.nextBoolean() ? syl[r.nextInt(syl.length)] : "");
            sb.append(Character.toUpperCase(n.charAt(0))).append(n.substring(1));
        }
        return sb.toString();
    }

    /** Procedural alien head. UV regions: cranium (0,0), eyes (48,48), accents (32,48). */
    static ModelDef head(SplittableRandom r) {
        ModelDef.PartDef root = new ModelDef.PartDef("root");
        ModelDef.PartDef head = new ModelDef.PartDef("head");
        root.children.put("head", head);
        int w = 6 + r.nextInt(5), h = 7 + r.nextInt(8), d = 6 + r.nextInt(5);
        head.cubes.add(new ModelDef.CubeDef(0, 0, -w / 2f, -h, -d / 2f, w, h, d, 0, 0, 0, false));
        // Eyes
        int eyes = 1 + r.nextInt(3);
        float eyeY = -h + 2 + r.nextInt(Math.max(1, h / 2));
        for (int i = 0; i < eyes; i++) {
            float ex = eyes == 1 ? -1 : -w / 2f + 1 + i * (w - 3f) / Math.max(1, eyes - 1);
            head.cubes.add(new ModelDef.CubeDef(48, 48, ex, eyeY, -d / 2f - 1, 2, 2, 1, 0, 0, 0, false));
        }
        // Antennae / horns
        if (r.nextBoolean()) {
            for (int side = -1; side <= 1; side += 2) {
                ModelDef.PartDef ant = new ModelDef.PartDef(side < 0 ? "antenna_right" : "antenna_left");
                ant.x = side * (w / 2f - 1);
                ant.y = -h;
                ant.zRot = side * (0.2f + r.nextFloat() * 0.5f);
                ant.xRot = -0.2f;
                int len = 3 + r.nextInt(5);
                ant.cubes.add(new ModelDef.CubeDef(32, 48, -0.5f, -len, -0.5f, 1, len, 1, 0, 0, 0, false));
                ant.cubes.add(new ModelDef.CubeDef(48, 48, -1, -len - 2, -1, 2, 2, 2, 0, 0, 0, false));
                head.children.put(ant.name, ant);
            }
        }
        // Mandibles / tentacles
        if (r.nextInt(3) == 0) {
            int n = 2 + r.nextInt(3);
            for (int i = 0; i < n; i++) {
                ModelDef.PartDef t = new ModelDef.PartDef("tentacle_" + i);
                t.x = -w / 2f + 1 + i * (w - 2f) / Math.max(1, n - 1);
                t.y = 0;
                t.z = -d / 2f + 1;
                t.xRot = 0.15f;
                int len = 2 + r.nextInt(4);
                t.cubes.add(new ModelDef.CubeDef(32, 48, -0.5f, 0, -0.5f, 1, len, 1, 0, 0, 0, false));
                head.children.put(t.name, t);
            }
        }
        // Fins
        if (r.nextInt(3) == 0) {
            head.cubes.add(new ModelDef.CubeDef(32, 48, -0.5f, -h - 3, -d / 2f + 1, 1, 3, d - 2, 0, 0, 0, false));
        }
        return new ModelDef(64, 64, root);
    }
}
