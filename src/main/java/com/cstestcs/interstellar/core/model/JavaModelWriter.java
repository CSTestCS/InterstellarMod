package com.cstestcs.interstellar.core.model;

import java.util.Locale;

/** Writes a {@link ModelDef} as a Blockbench-style "Modded Entity" Java class (the format the races folder accepts). */
public final class JavaModelWriter {
    private JavaModelWriter() {}

    public static String write(String className, ModelDef def) {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by Interstellar in the Blockbench \"Modded Entity\" format (Mojang mappings).\n");
        sb.append("// Open it in Blockbench (File > Import > Java model) or edit the numbers directly.\n");
        sb.append("// Only createBodyLayer() is read by the mod; a part named \"head\" is aligned with the mob's head pivot.\n\n");
        sb.append("public class ").append(className).append("<T extends Entity> extends EntityModel<T> {\n");
        sb.append("\tpublic static LayerDefinition createBodyLayer() {\n");
        sb.append("\t\tMeshDefinition meshdefinition = new MeshDefinition();\n");
        sb.append("\t\tPartDefinition partdefinition = meshdefinition.getRoot();\n\n");
        for (ModelDef.PartDef child : def.root.children.values()) writePart(sb, "partdefinition", child);
        sb.append("\t\treturn LayerDefinition.create(meshdefinition, ").append(def.textureWidth).append(", ").append(def.textureHeight).append(");\n");
        sb.append("\t}\n}\n");
        return sb.toString();
    }

    private static void writePart(StringBuilder sb, String parentVar, ModelDef.PartDef p) {
        String var = p.name.replaceAll("[^A-Za-z0-9_]", "_");
        sb.append("\t\tPartDefinition ").append(var).append(" = ").append(parentVar).append(".addOrReplaceChild(\"").append(p.name).append("\", CubeListBuilder.create()");
        for (ModelDef.CubeDef c : p.cubes) {
            sb.append(".texOffs(").append(c.u()).append(", ").append(c.v()).append(")");
            if (c.mirror()) sb.append(".mirror()");
            sb.append(".addBox(").append(f(c.x())).append(", ").append(f(c.y())).append(", ").append(f(c.z())).append(", ")
                    .append(f(c.w())).append(", ").append(f(c.h())).append(", ").append(f(c.d())).append(", new CubeDeformation(")
                    .append(f(c.growX())).append("))");
            if (c.mirror()) sb.append(".mirror(false)");
        }
        sb.append(", ");
        if (p.xRot != 0 || p.yRot != 0 || p.zRot != 0) {
            sb.append("PartPose.offsetAndRotation(").append(f(p.x)).append(", ").append(f(p.y)).append(", ").append(f(p.z)).append(", ")
                    .append(f(p.xRot)).append(", ").append(f(p.yRot)).append(", ").append(f(p.zRot)).append(")");
        } else {
            sb.append("PartPose.offset(").append(f(p.x)).append(", ").append(f(p.y)).append(", ").append(f(p.z)).append(")");
        }
        sb.append(");\n\n");
        for (ModelDef.PartDef c : p.children.values()) writePart(sb, var, c);
    }

    private static String f(float v) {
        return String.format(Locale.ROOT, "%.4fF", v);
    }
}
