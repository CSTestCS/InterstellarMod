package com.cstestcs.interstellar.client.gun;

import com.cstestcs.interstellar.Interstellar;
import com.cstestcs.interstellar.core.gun.GunBuild;
import com.cstestcs.interstellar.core.gun.GunData;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.Reader;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import net.minecraft.client.Minecraft;
import org.joml.Matrix4f;
import org.jspecify.annotations.Nullable;

/**
 * Where each slot's part attaches on each weapon family ({@code assets/interstellar/gun_anchors.json}, generated by
 * tools/gun_models.py): the part's reference point moves to the family's anchor and is scaled about it, so the same
 * part sits where that weapon has it. Muzzles follow the end of the fitted barrel. Read again after a resource reload.
 */
public final class GunAnchors {
    private record Anchor(float x, float y, float z, float sx, float sy, float sz) {}

    private static @Nullable GunAnchors loaded;
    private final Map<String, float[]> pivots = new HashMap<>();
    private final Set<String> foregrips = new HashSet<>();
    private final Map<String, Float> barrelEnds = new HashMap<>();
    private final Map<String, Map<String, Anchor>> archetypes = new HashMap<>();

    private GunAnchors() {}

    static void invalidate() {
        loaded = null;
    }

    private static GunAnchors get() {
        GunAnchors a = loaded;
        if (a == null) {
            a = new GunAnchors();
            try {
                var res = Minecraft.getInstance().getResourceManager().getResource(Interstellar.id("gun_anchors.json"));
                if (res.isPresent()) {
                    try (Reader r = res.get().openAsReader()) {
                        a.read(JsonParser.parseReader(r).getAsJsonObject());
                    }
                }
            } catch (Exception e) {
                Interstellar.LOGGER.warn("Could not read gun_anchors.json: {}", e.toString());
            }
            loaded = a;
        }
        return a;
    }

    private void read(JsonObject o) {
        for (Map.Entry<String, JsonElement> e : o.getAsJsonObject("pivots").entrySet()) pivots.put(e.getKey(), floats(e.getValue()));
        for (JsonElement e : o.getAsJsonArray("foregrips")) foregrips.add(e.getAsString());
        if (o.has("barrel_ends")) {
            for (Map.Entry<String, JsonElement> e : o.getAsJsonObject("barrel_ends").entrySet()) barrelEnds.put(e.getKey(), e.getValue().getAsFloat());
        }
        for (Map.Entry<String, JsonElement> a : o.getAsJsonObject("archetypes").entrySet()) {
            Map<String, Anchor> slots = new HashMap<>();
            for (Map.Entry<String, JsonElement> s : a.getValue().getAsJsonObject().entrySet()) {
                float[] f = floats(s.getValue());
                slots.put(s.getKey(), new Anchor(f[0], f[1], f[2], f[3], f[4], f[5]));
            }
            archetypes.put(a.getKey(), slots);
        }
    }

    private static float[] floats(JsonElement e) {
        var a = e.getAsJsonArray();
        float[] f = new float[a.size()];
        for (int i = 0; i < f.length; i++) f[i] = a.get(i).getAsFloat();
        return f;
    }

    /** Key identifying the placement (for render state caching), or null when the part stays where it was designed. */
    static @Nullable String key(GunBuild build, String slot) {
        GunAnchors a = get();
        Map<String, Anchor> slots = a.archetypes.get(build.archetype());
        if (slots == null) return null;
        String barrel = part(build, "barrel");
        return build.archetype() + "/" + slot + "/" + part(build, slot) + (slot.equals("muzzle") ? "/" + barrel : "");
    }

    /** Transform (block units) placing a slot's part on the build's family, or null when it stays as designed. */
    static @Nullable Matrix4f transform(GunBuild build, String slot) {
        GunAnchors a = get();
        Map<String, Anchor> slots = a.archetypes.get(build.archetype());
        if (slots == null) return null;
        String pid = part(build, slot);
        String key = slot.equals("grip") && pid != null && a.foregrips.contains(pid) ? "foregrip" : slot;
        float[] pivot = a.pivots.get(key);
        if (pivot == null) return null;
        Anchor anchor = slots.get(key);
        float tx, ty, tz, sx, sy, sz;
        if (anchor == null) {
            tx = pivot[0];
            ty = pivot[1];
            tz = pivot[2];
            sx = sy = sz = 1;
        } else {
            tx = anchor.x;
            ty = anchor.y;
            tz = anchor.z;
            sx = anchor.sx;
            sy = anchor.sy;
            sz = anchor.sz;
        }
        String barrel = part(build, "barrel");
        if (slot.equals("muzzle") && barrel != null) {
            // Muzzles sit on the end of the fitted barrel.
            float[] bp = a.pivots.get("barrel");
            Anchor b = slots.get("barrel");
            float end = a.barrelEnds.getOrDefault(barrel, 17f);
            float bx = b == null ? bp[0] : b.x, bsx = b == null ? 1 : b.sx;
            tx = bx + (end - bp[0]) * bsx;
            ty = b == null ? bp[1] : b.y;
            tz = b == null ? bp[2] : b.z;
        } else if (anchor == null) {
            return null;
        }
        return new Matrix4f().translate(tx / 16f, ty / 16f, tz / 16f).scale(sx, sy, sz).translate(-pivot[0] / 16f, -pivot[1] / 16f, -pivot[2] / 16f);
    }

    private static @Nullable String part(GunBuild build, String slot) {
        GunData.Slot s = GunData.Slot.byKey(slot);
        GunBuild.Choice c = s == null ? null : build.parts().get(s);
        return c == null ? null : c.part();
    }
}
