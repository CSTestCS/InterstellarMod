package com.cstestcs.interstellar.space.planet;

import com.cstestcs.interstellar.Interstellar;
import com.cstestcs.interstellar.core.space.ForeignWorlds;
import com.cstestcs.interstellar.core.space.PlanetGenome;
import com.cstestcs.interstellar.core.space.PlanetShape;
import com.cstestcs.interstellar.registry.ModAttachments;
import com.cstestcs.interstellar.registry.ModBlocks;
import com.cstestcs.interstellar.space.SpaceTravel;
import java.util.ArrayDeque;
import java.util.Deque;
import net.minecraft.core.BlockPos;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.chunk.LevelChunk;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.level.ChunkEvent;
import net.neoforged.neoforge.event.tick.LevelTickEvent;
import org.jspecify.annotations.Nullable;

/**
 * Fills space with procedural planets. Space chunks are generated by {@link SpaceChunkGenerator}, which writes the
 * planets reaching into each chunk while the chunk is generated (off the main thread, with no block updates). Space
 * chunks generated by older versions, before that, get their planets added once when they first load.
 * <p>
 * Each planet is drawn from its genome: its random default block, its seas, and patches of its species' blocks;
 * cubes for most, irregular rocks for end-like planets, wrapped in an atmosphere shell.
 */
@EventBusSubscriber(modid = Interstellar.MODID)
public final class SpacePlanets {
    private static final Deque<Long> PENDING = new ArrayDeque<>();

    /** Where planet blocks are written: a chunk being generated, or the live level. */
    interface Sink {
        BlockState get(BlockPos pos);

        void set(BlockPos pos, BlockState state);
    }

    private SpacePlanets() {}

    // ------------------------------------------------------------------ chunks from older versions

    @SubscribeEvent
    static void onChunkLoad(ChunkEvent.Load event) {
        if (!(event.getLevel() instanceof ServerLevel level) || !SpaceTravel.isSpace(level)) return;
        if (level.getChunkSource().getGenerator() instanceof SpaceChunkGenerator && event.isNewChunk()) return; // built during generation
        LevelChunk chunk = event.getChunk();
        if (Boolean.TRUE.equals(chunk.getData(ModAttachments.PLANETS_BUILT))) return;
        synchronized (PENDING) {
            PENDING.add(((long) chunk.getPos().x() << 32) | (chunk.getPos().z() & 0xFFFFFFFFL));
        }
    }

    @SubscribeEvent
    static void onLevelTick(LevelTickEvent.Post event) {
        if (!(event.getLevel() instanceof ServerLevel level) || !SpaceTravel.isSpace(level)) return;
        for (int n = 0; n < 4; n++) {
            long packed;
            synchronized (PENDING) {
                if (PENDING.isEmpty()) return;
                packed = PENDING.poll();
            }
            ChunkPos pos = new ChunkPos((int) (packed >> 32), (int) packed);
            LevelChunk chunk = level.getChunkSource().getChunkNow(pos.x(), pos.z());
            if (chunk == null || Boolean.TRUE.equals(chunk.getData(ModAttachments.PLANETS_BUILT))) continue;
            int flags = Block.UPDATE_CLIENTS | Block.UPDATE_KNOWN_SHAPE;
            build(level.registryAccess(), pos, new Sink() {
                @Override
                public BlockState get(BlockPos p) {
                    return chunk.getBlockState(p);
                }

                @Override
                public void set(BlockPos p, BlockState state) {
                    level.setBlock(p, state, flags);
                }
            });
            chunk.setData(ModAttachments.PLANETS_BUILT, true);
        }
    }

    // ------------------------------------------------------------------ building

    /** Writes every procedural planet part that falls into a chunk. */
    static void build(HolderLookup.Provider registries, ChunkPos chunk, Sink sink) {
        int cx0 = chunk.getMinBlockX(), cz0 = chunk.getMinBlockZ();
        for (PlanetGenome g : PlanetGenome.near(cx0 + 8, cz0 + 8, 40)) {
            int[] a = g.atmosphere();
            if (a[3] <= cx0 || a[0] >= cx0 + 16 || a[5] <= cz0 || a[2] >= cz0 + 16) continue;
            buildPart(registries, g, cx0, cz0, sink);
        }
    }

    /** Writes into a chunk being generated. */
    static void build(HolderLookup.Provider registries, ChunkAccess chunk) {
        build(registries, chunk.getPos(), new Sink() {
            @Override
            public BlockState get(BlockPos p) {
                return chunk.getBlockState(p);
            }

            @Override
            public void set(BlockPos p, BlockState state) {
                chunk.setBlockState(p, state);
            }
        });
    }

    private static void buildPart(HolderLookup.Provider registries, PlanetGenome g, int cx0, int cz0, Sink sink) {
        BlockState stone = PlanetPools.defaultBlock(g, registries);
        BlockState sea = seaLook(g, registries);
        ForeignWorlds.Theme theme = ForeignWorlds.all().get(g.species()).theme();
        BlockState top = block(theme.topBlock), accent = block(theme.accentBlock);
        PlanetShape shape = g.shape();
        int n = g.size();
        double seaShare = sea == null ? -1 : (g.seaLevel() - 40) / 160.0; // more sea the higher the sea level
        int[] a = shape.atmosphere();
        BlockState atmosphere = ModBlocks.ATMOSPHERE.get().defaultBlockState();
        BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos();
        int x0 = g.x() - n / 2, y0 = g.y() - n / 2, z0 = g.z() - n / 2;
        for (int x = Math.max(a[0], cx0); x < Math.min(a[3], cx0 + 16); x++) {
            for (int z = Math.max(a[2], cz0); z < Math.min(a[5], cz0 + 16); z++) {
                for (int y = a[1]; y < a[4]; y++) {
                    if (shape.solidAt(x, y, z)) {
                        boolean surface = !shape.solidAt(x + 1, y, z) || !shape.solidAt(x - 1, y, z) || !shape.solidAt(x, y + 1, z)
                                || !shape.solidAt(x, y - 1, z) || !shape.solidAt(x, y, z + 1) || !shape.solidAt(x, y, z - 1);
                        BlockState s = stone;
                        if (surface) {
                            int h = hash(x, y, z, g.seed());
                            if (sea != null && continent(x - x0, y - y0, z - z0, n, g.seed()) < seaShare) s = sea;
                            else if (h % 11 == 0) s = accent;
                            else if (h % 4 == 0) s = top;
                        }
                        sink.set(p.set(x, y, z), s);
                    } else if (shape.atmosphereShellAt(x, y, z) && sink.get(p.set(x, y, z)).isAir()) {
                        sink.set(p, atmosphere);
                    }
                }
            }
        }
    }

    /** How the planet's seas look from space (liquids would flow out). */
    private static @Nullable BlockState seaLook(PlanetGenome g, HolderLookup.Provider registries) {
        if (g.terrain() == PlanetGenome.Terrain.END || g.terrain() == PlanetGenome.Terrain.FLOATING_ISLANDS) return null;
        return switch (g.fluid()) {
            case WATER -> block("minecraft:blue_concrete");
            case LAVA -> Blocks.MAGMA_BLOCK.defaultBlockState();
            case BLOCK -> PlanetPools.defaultFluid(g, registries);
        };
    }

    static double continent(int x, int y, int z, int n, long seed) {
        double c = (n - 1) / 2.0;
        double dx = (x - c) / n, dy = (y - c) / n, dz = (z - c) / n;
        double v = 0;
        for (int i = 0; i < 3; i++) {
            long s = seed + i * 0x632BE59BD9B4E019L;
            double fx = 3 + (s & 3), fy = 3 + ((s >>> 2) & 3), fz = 3 + ((s >>> 4) & 3);
            v += Math.sin(dx * fx * 6.28 + (s >>> 8 & 15)) * Math.cos(dz * fz * 6.28 + (s >>> 12 & 15)) * Math.sin(dy * fy * 6.28 + 1 + (s >>> 16 & 15)) / (i + 1);
        }
        return v;
    }

    static int hash(int x, int y, int z, long seed) {
        long h = seed ^ (x * 73856093L) ^ (y * 19349663L) ^ (z * 83492791L);
        h = (h ^ (h >>> 31)) * 0x7fb5d329728ea185L;
        return (int) ((h ^ (h >>> 27)) & 0x7fffffff);
    }

    private static BlockState block(String id) {
        return BuiltInRegistries.BLOCK.getOptional(Identifier.parse(id)).orElse(Blocks.STONE).defaultBlockState();
    }
}
